package Hieracal;

public class Professor extends College{
	
	protected int Profid;
	protected String Profname;
	public int getProfid() {
		return Profid;
	}
	public void setProfid(int profid) {
		Profid = profid;
	}
	public String getProfname() {
		return Profname;
	}
	public void setProfname(String profname) {
		Profname = profname;
	}
	 
	
	

}
