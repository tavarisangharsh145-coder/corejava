package studentdetails;

public class StudentBeans {

	private int stdrollno;
	private String stdname;
	private double stdfees;
	
	// Setter method
	public void setStdrollno(int rollno)
	{
		this.stdrollno=rollno;
	}
	
	//Getter method
	public int getstdrollno()
	{
		return stdrollno;
	}
	
	//Setter method
	public void setStdname(String name)
	{
		this.stdname=name;
	}
	
	//Getter method
	public String getStdname()
	{
		return stdname;
	}
	
	//Setter method
	public void setStdfees(double fees)
	{
		this.stdfees=fees;
	}
	
	//Getter method
	public double getStdfees()
	{
		return stdfees;
	}
	
	
}

	

